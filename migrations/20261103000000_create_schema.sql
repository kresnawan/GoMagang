CREATE TABLE pengguna (
    id_pengguna INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE tim_mb (
    id_pengguna INTEGER PRIMARY KEY REFERENCES pengguna (id_pengguna),
    nama VARCHAR(255),
    no_hp VARCHAR(20)
);

CREATE TABLE mahasiswa (
    nim CHAR(15) PRIMARY KEY,
    id_pengguna INTEGER NOT NULL UNIQUE REFERENCES pengguna (id_pengguna),
    nama VARCHAR(255),
    program_studi VARCHAR(255),
    ipk NUMERIC(3, 2),
    no_hp VARCHAR(20)
);

CREATE TABLE perusahaan_mitra (
    id_perusahaan INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_perusahaan VARCHAR(255) NOT NULL
);

CREATE TABLE periode_pendaftaran (
    id_periode INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catatan VARCHAR(255),
    waktu_mulai TIMESTAMP NOT NULL,
    waktu_tutup TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE posisi_magang (
    id_posisi INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_perusahaan INTEGER NOT NULL REFERENCES perusahaan_mitra (id_perusahaan),
    posisi VARCHAR(255) NOT NULL,
    deskripsi_persyaratan TEXT NOT NULL,
    kuota_total INTEGER NOT NULL,
    sisa_kuota INTEGER NOT NULL,
    id_periode INTEGER NOT NULL REFERENCES periode_pendaftaran (id_periode)
);

CREATE TABLE status_pendaftaran (
    id_status INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(255) NOT NULL
);

CREATE TABLE pendaftaran (
    id_pendaftaran INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nim CHAR(15) NOT NULL REFERENCES mahasiswa (nim),
    id_posisi INTEGER NOT NULL REFERENCES posisi_magang (id_posisi),
    id_status INTEGER NOT NULL REFERENCES status_pendaftaran (id_status),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE log_status (
    id_log INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pendaftaran INTEGER NOT NULL REFERENCES pendaftaran (id_pendaftaran),
    id_pengubah INTEGER REFERENCES tim_mb (id_pengguna),
    status_lama INTEGER REFERENCES status_pendaftaran (id_status),
    status_baru INTEGER NOT NULL REFERENCES status_pendaftaran (id_status),
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE berkas_pendaftaran (
    id_berkas INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pendaftaran INTEGER NOT NULL REFERENCES pendaftaran (id_pendaftaran),
    jenis_berkas VARCHAR(255) NOT NULL,
    nama_berkas VARCHAR(255) NOT NULL,
    ukuran_berkas INTEGER NOT NULL
);

CREATE TABLE jadwal_seleksi_substansi (
    id_jadwal INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pendaftaran INTEGER NOT NULL UNIQUE REFERENCES pendaftaran (id_pendaftaran),
    tanggal DATE NOT NULL,
    jam TIME NOT NULL,
    lokasi VARCHAR(255) NOT NULL
);

CREATE TABLE surat_keterangan (
    id_surat INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pendaftaran INTEGER NOT NULL UNIQUE REFERENCES pendaftaran (id_pendaftaran),
    nama_berkas VARCHAR(255) NOT NULL,
    ukuran_berkas INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE plotting_dpm (
    id_plotting INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pendaftaran INTEGER NOT NULL UNIQUE REFERENCES pendaftaran (id_pendaftaran),
    nama_dpm VARCHAR(255) NOT NULL,
    kontak_dpm VARCHAR(255) NOT NULL
);

CREATE TABLE mata_kuliah_konversi (
    id_mk_konversi INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mk_konversi VARCHAR(255) NOT NULL,
    mk_asal VARCHAR(255) NOT NULL,
    sks INTEGER NOT NULL
);

CREATE TABLE penyetaraan_mk (
    id_penyetaraan INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mk_konversi INTEGER NOT NULL REFERENCES mata_kuliah_konversi (id_mk_konversi),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    id_pendaftaran INTEGER NOT NULL REFERENCES pendaftaran (id_pendaftaran)
);

CREATE TABLE templat_sp_dpa (
    id_templat INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tautan_templat VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT now()
);
